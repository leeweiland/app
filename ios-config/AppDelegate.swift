    // Capacitor's PushNotifications plugin listens for these two
    // NotificationCenter posts internally to fire its JS-side
    // 'registration'/'registrationError' events — without relaying iOS's
    // own APNs registration callbacks into them here, register() still
    // successfully kicks off registerForRemoteNotifications() (which is
    // why it resolves without error and the permission prompt works),
    // but nothing ever comes back to JS: no token, no error, forever.
    // This isn't part of Capacitor's default generated template, and
    // Codemagic's `rm -rf ios && npx cap add ios` regenerates
    // AppDelegate.swift from that bare template on every single build,
    // so this has to be layered back in every time (same reason
    // GoogleService-Info.plist/App.entitlements are copied in from this
    // same ios-config/ directory) rather than edited once and left alone.
    func application(_ application: UIApplication, didRegisterForRemoteNotificationsWithDeviceToken deviceToken: Data) {
        NotificationCenter.default.post(name: .capacitorDidRegisterForRemoteNotifications, object: deviceToken)
    }

    func application(_ application: UIApplication, didFailToRegisterForRemoteNotificationsWithError error: Error) {
        NotificationCenter.default.post(name: .capacitorDidFailToRegisterForRemoteNotifications, object: error)
    }

    func application(_ application: UIApplication,
                     configurationForConnecting connectingSceneSession: UISceneSession,
                     options: UIScene.ConnectionOptions) -> UISceneConfiguration {
        let config = UISceneConfiguration(name: "Default Configuration",
                                          sessionRole: connectingSceneSession.role)
        config.delegateClass = SceneDelegate.self
        return config
    }
